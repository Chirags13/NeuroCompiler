// Shared helpers: API, formatting, DOM building.
export async function api(path, opts = {}) {
  const r = await fetch(path, opts);
  if (!r.ok) {
    let msg = r.statusText;
    try { msg = (await r.json()).detail || msg; } catch (_) { /* ignore */ }
    throw new Error(msg);
  }
  return r.json();
}

export const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

export function h(tag, attrs = {}, ...kids) {
  const e = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v == null || v === false) continue;
    if (k === "class") e.className = v;
    else if (k === "html") e.innerHTML = v;
    else if (k.startsWith("on")) e.addEventListener(k.slice(2), v);
    else e.setAttribute(k, v === true ? "" : v);
  }
  for (const kid of kids.flat()) if (kid != null && kid !== false) e.append(kid.nodeType ? kid : document.createTextNode(kid));
  return e;
}

export const x = (v, d = 3) => (v == null || isNaN(v) ? "–" : `${Number(v).toFixed(d)}×`);
export const pct = (v, d = 2) => (v == null || isNaN(v) ? "–" : `${v >= 1 ? "+" : ""}${((v - 1) * 100).toFixed(d)}%`);
export const ms = (v) => (v == null || isNaN(v) ? "–" : v >= 1000 ? `${(v / 1000).toFixed(2)} s` : `${v.toFixed(v < 10 ? 2 : 1)} ms`);
export const secs = (v) => (v == null || isNaN(v) ? "–" : v >= 120 ? `${(v / 60).toFixed(1)} min` : `${v.toFixed(v < 10 ? 2 : 0)} s`);
export const cls = (v, t = 0.01) => (v == null ? "neu" : v > 1 + t ? "pos" : v < 1 - t ? "neg" : "neu");
export const ci = (c) => (c && c[0] != null ? `[${Number(c[0]).toFixed(3)}, ${Number(c[1]).toFixed(3)}]` : "");
export const ago = (t) => {
  const s = Math.max(0, Date.now() / 1000 - t);
  return s < 60 ? `${s.toFixed(0)}s ago` : s < 3600 ? `${(s / 60).toFixed(0)}m ago` : `${(s / 3600).toFixed(1)}h ago`;
};

let toastTimer;
export function toast(msg) {
  let t = document.getElementById("toast");
  t.textContent = msg;
  t.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.classList.remove("show"), 3200);
}

